import pytest
import soundfile as sf
import numpy as np
from pathlib import Path
from typer.testing import CliRunner

from music_re.cli import app
from music_re.workspace import WorkspaceManager
from music_re.core.pipeline import run_pipeline

runner = CliRunner()

def test_full_pipeline_with_dawproject_and_specialized_backends(tmp_path):
    # Create 2 seconds synthetic song with vocal harmonic signal and bass
    sr = 22050
    t = np.linspace(0, 2.0, int(sr * 2.0), endpoint=False)
    # 440 Hz rich harmonic square signal for clear pitch detection
    vocal = 0.5 * np.sign(np.sin(2 * np.pi * 440.0 * t)).astype(np.float32)
    bass = 0.4 * np.sin(2 * np.pi * 110.0 * t).astype(np.float32)
    stereo = np.stack([vocal + bass, vocal + bass], axis=-1)
    
    song_wav = tmp_path / "song.wav"
    sf.write(str(song_wav), stereo, sr)
    
    cache_root = tmp_path / "cache"
    ws = WorkspaceManager(cache_root=cache_root)
    
    # 1. Run deconstruct
    res = runner.invoke(app, [
        "deconstruct", str(song_wav),
        "--cache-root", str(cache_root),
        "--profile", "fast",
        "--device", "cpu",
    ])
    assert res.exit_code == 0
    
    # Verify vocal MIDI contains pitch bends generated by crepe
    manifest = ws.get_manifest(song_wav)
    assert "vocals" in manifest.midis
    import pretty_midi
    vocal_pm = pretty_midi.PrettyMIDI(manifest.midis["vocals"])
    assert len(vocal_pm.instruments) > 0
    # CREPE generates continuous pitch bends
    assert len(vocal_pm.instruments[0].pitch_bends) > 0
    
    # 2. Export DAWproject
    out_dawproject = tmp_path / "export.dawproject"
    res_exp = runner.invoke(app, [
        "export", str(song_wav),
        "--cache-root", str(cache_root),
        "--profile", "fast",
        "--out", str(out_dawproject),
        "--dawproject",
    ])
    assert res_exp.exit_code == 0
    assert out_dawproject.is_file()
    assert out_dawproject.stat().st_size > 0
    
    # Verify DAWproject opens and contains audio tracks, note tracks, transport
    from dawproject import DawProject
    proj = DawProject.load_project(str(out_dawproject))
    assert proj.application.name == "MusicRE"
    assert proj.transport is not None
    assert len(proj.structure) >= 2 # Master + stems
